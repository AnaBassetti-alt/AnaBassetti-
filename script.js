const menu = document.querySelector('.menu');
const nav = document.querySelector('#navigation');
let language = 'pt';
function closeMenu() { menu.setAttribute('aria-expanded','false'); nav.classList.remove('open'); menu.setAttribute('aria-label', language === 'pt' ? 'Abrir menu' : 'Open menu'); }
function renderLanguage(lang) {
 language = lang; document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
 document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = translations[el.dataset.i18n][lang === 'pt' ? 0 : 1]; });
 document.querySelectorAll('[data-lang]').forEach(el => el.setAttribute('aria-pressed', String(el.dataset.lang === lang)));
 nav.setAttribute('aria-label', lang === 'pt' ? 'Navegação principal' : 'Main navigation');
 menu.setAttribute('aria-label', menu.getAttribute('aria-expanded') === 'true' ? (lang === 'pt' ? 'Fechar menu' : 'Close menu') : (lang === 'pt' ? 'Abrir menu' : 'Open menu'));
 document.querySelectorAll('.project-link').forEach(el => el.textContent = lang === 'pt' ? 'Ver projeto ↗' : 'View project ↗');
 try { localStorage.setItem('bassetti-language', lang); } catch (_) {}
}
function setupLinks() {
 Object.entries(contacts).forEach(([key,value]) => { if (!value) return; const row = document.querySelector(`[data-contact="${key}"]`); const a = document.createElement('a'); a.href = key === 'email' ? 'mailto:'+value : value; a.textContent = value; row.querySelector('.contact-status').replaceWith(a); });
 document.querySelectorAll('.project').forEach((card,i) => { if (!projectLinks[i]) return; const a = document.createElement('a'); a.href = projectLinks[i]; a.className = 'button project-link'; card.querySelector('.project-copy').append(a); });
}
function setupNavigation() {
 menu.addEventListener('click', () => { if (menu.getAttribute('aria-expanded') === 'true') closeMenu(); else { nav.classList.add('open'); menu.setAttribute('aria-expanded','true'); menu.setAttribute('aria-label', language === 'pt' ? 'Fechar menu' : 'Close menu'); } });
 nav.querySelectorAll('a').forEach(a => a.addEventListener('click', closeMenu));
 document.addEventListener('keydown', e => { if(e.key === 'Escape' && nav.classList.contains('open')) { closeMenu(); menu.focus(); } });
 window.matchMedia('(min-width: 901px)').addEventListener('change', closeMenu);
 const sections = [...document.querySelectorAll('main section[id]')];
 let scheduled = false;
 function updateActive(){ scheduled = false; const y = window.scrollY + 120; let current = sections[0].id; sections.forEach(s => {if(s.offsetTop <= y) current=s.id;}); if(current === 'experience') current='projects'; if(window.scrollY + innerHeight >= document.documentElement.scrollHeight - 4) current='contact'; nav.querySelectorAll('a').forEach(a => { const active=a.hash === '#'+current; if(active) a.setAttribute('aria-current','location'); else a.removeAttribute('aria-current'); }); }
 window.addEventListener('scroll', () => {if(!scheduled){scheduled=true;requestAnimationFrame(updateActive);}}, {passive:true}); window.addEventListener('resize',updateActive); updateActive();
}
function setupMotion(){ if(!('IntersectionObserver' in window) || matchMedia('(prefers-reduced-motion: reduce)').matches) return; const observer=new IntersectionObserver(entries=>entries.forEach(e=>{if(e.isIntersecting){e.target.classList.add('visible');observer.unobserve(e.target);}}),{threshold:0.08}); document.querySelectorAll('.reveal').forEach(el=>{el.classList.add('motion');observer.observe(el);}); }
setupLinks(); setupNavigation(); setupMotion();
